var (
	//go:embed public/text/defacto2.txt
	brand []byte
	//go:embed public/**/*
	public embed.FS
	//go:embed view/**/*
	view    embed.FS
	version string // version is generated by the GoReleaser ldflags.
)

func main() {
	os.Exit(run())
}

func run() int {
	// Initialize a temporary logger, and get then print the environment variable configurations.
	l := logs.Default()
	slog.SetDefault(l)

	envConfig, err := environmentVars()
	if err != nil {
		l.Error("environment variables",
			slog.String("parsing_error", "does the variable contain an invalid value?"),
			slog.Any("error", err))
		return int(flags.GenericErr)
	}

	// Parse any application commands and flags, and if appropriate run the request and exit to
	// the terminal.
	const quit = 0
	if exitCode := flagParser(l, os.Stdout, envConfig); exitCode >= quit {
		return int(exitCode)
	}

	// Configure the sl application logger and the logo writer.
	// Startup summary output is written to stdout (discarded in quiet mode) so
	// system and file logs stay focused on runtime events and errors.
	fileLog, closeLogs := openLogFiles(envConfig)
	defer closeLogs()

	sl, cl, logo := setupWriters(*envConfig, fileLog)
	logErr := func(msg string, err error) {
		sl.Error(msg, slog.Any("error", err))
	}
	warnErr := func(msg string, err error) {
		sl.Warn(msg, slog.Any("error", err))
	}

	// In quiet mode (e.g. systemd), surface any configuration issues immediately.
	if envConfig.Quiet.Bool() {
		envConfig.Configurations(cl)
	}

	// Connect to the database. Even if the database cannot connect,
	// the web server will continue to run with limited functionality.
	opened, err := openDatabase(sl)
	if err != nil {
		return int(flags.GenericErr)
	}
	defer func() {
		if err := opened.db.Close(); err != nil {
			warnErr("close database connection failure", err)
		}
	}()

	// Clean stale temporary directories created by this application.
	const stale = 3 * 24 * time.Hour
	if err := dir.CleanTemp(stale); err != nil {
		logErr("abort clean stale temp", err)
	}

	// Start the web server.
	parent := context.Background()
	signals := []os.Signal{os.Interrupt, syscall.SIGTERM}
	ctx, stop := signal.NotifyContext(parent, signals...)
	defer stop()

	var db *sql.DB
	if opened.connected {
		db = opened.db
	}
	serv := initialisation(ctx, db, *envConfig)
	serv.DBVersion = opened.version

	tidbitIndex(ctx, sl, serv, opened)

	h := serv.Handler(ctx, sl, opened.db)
	if err := serv.Print(logo); err != nil {
		warnErr("print server startup", err)
	}
	if envConfig.Quiet.Bool() {
		if opened.version != "" {
			sl.Info("Database", slog.String("version", opened.version))
		}
		config.TempInfo(sl)
		opening(sl, serv.RecordCount)
	}

	if err := serv.Start(ctx, sl, h, *envConfig); err != nil {
		logErr("web server startup failure", err)
		return int(flags.GenericErr)
	}

	sl.Info("Shutdown", slog.String("Triggered", "Signal received"))
	return int(flags.ExitOK)
}

func openLogFiles(cc *config.Config) (logs.Files, func()) {
	const format = "open log files: %w"
	noop := func() {}
	if cc == nil {
		return logs.NoFiles(), noop
	}
	root := string(cc.AbsLog)
	if root == "" || !cc.ProdMode.Bool() {
		return logs.NoFiles(), noop
	}
	const nothing = "" // replace with logs.NameDebug to write debug log reports
	fileLog, err := logs.OpenFiles(root, logs.NameErr, logs.NameInfo, nothing)
	if err != nil {
		log.Println(fmt.Errorf(format, err))
		return logs.NoFiles(), noop
	}
	return fileLog, func() {
		if err := fileLog.Close(); err != nil {
			log.Println(err)
		}
	}
}

type state struct {
	db        *sql.DB
	version   string
	connected bool
}

func openDatabase(sl *slog.Logger) (state, error) {
	if err := nils.Check(sl); err != nil {
		return state{}, fmt.Errorf("open database: %w", err)
	}
	db, err := postgres.Open()
	connected := err == nil && db != nil
	if err != nil {
		sl.Error("cannot initialize the database", slog.Any("error", err))
	}
	if db == nil {
		var soErr error
		db, soErr = sql.Open("pgx", "")
		if soErr != nil || db == nil {
			sl.Error("cannot initialize the placeholder database", slog.Any("error", soErr))
			return state{}, fmt.Errorf("placeholder database: %w", soErr)
		}
	}

	var ver string
	if connected {
		var database postgres.Version
		if err := database.Query(db); err != nil {
			sl.Error("postgres cannot run the version query", slog.Any("error", err))
		} else {
			ver = strings.TrimPrefix(database.String(), "and using ")
		}
	}
	return state{db: db, version: ver, connected: connected}, nil
}

func tidbitIndex(ctx context.Context, sl *slog.Logger, serv *handler.Server, dbs state) {
	if err := nils.Check(ctx, sl, serv); err != nil {
		return
	}
	go func() {
		if err := serv.TidbitIndex.NewIndex(serv.Public, tidbit.Dir); err != nil {
			sl.Error("tidbit index", slog.Any("error", err))
			return
		}
		docs, terms := serv.TidbitIndex.Stats()
		sl.Info("Indexed Tidbits",
			slog.Int("Documents", docs),
			slog.Int64("SearchTerms", terms),
		)
	}()
	if dbs.connected && dbs.db != nil {
		go func() {
			tidbit.Startup(ctx, sl, dbs.db)
		}()
	}
}

func setupWriters(cc config.Config, lf logs.Files) (sl, cl *slog.Logger, logo io.Writer) {
	// configure logo to stdout so it is ignored by systemd and the operating system
	logo = os.Stdout
	// general slog and level configuration used by the website
	flag := logs.Defaults
	stdmin := logs.LevelInfo
	if quiet := bool(cc.Quiet); quiet {
		logo = io.Discard
		stdmin = logs.LevelError
		flag = logs.Quiets
	}

	// configure the server logger and make it the default
	sl = lf.New(stdmin, flag)
	slog.SetDefault(sl)

	// configuration command line logger flags
	flag = logs.Configurations
	stdmin = logs.LevelInfo

	if quiet := bool(cc.Quiet); quiet {
		stdmin = logs.LevelError
	}

	// print the server configuration and command line flag output to stdout
	cf := logs.NoFiles()
	cl = cf.New(stdmin, flag)
	return sl, cl, logo
}

// environmentVars parses environment variables into a Config with defaults
// and applies GOMAXPROCS if configured.
func environmentVars() (*config.Config, error) {
	const format = "environment variables: %w"
	cc := config.Config{
		DatabaseURL:   postgres.DefaultURL,
		HTTPPort:      config.StdCustom,
		SessionMaxAge: config.SessionHours,
		Compression:   true,
		ProdMode:      true,
		ReadOnly:      true,
	}
	if err := env.Parse(&cc); err != nil {
		return nil, fmt.Errorf(format, err)
	}

	cc.Override()
	if i := cc.MaxProcs; i > 0 {
		runtime.GOMAXPROCS(int(i))
	}

	return &cc, nil
}

// initialisation is used to create the server controller instance.
//
// The configuration returns a reference type to make the values immutable.
func initialisation(ctx context.Context, db *sql.DB, cc config.Config) *handler.Server {
	c := handler.Server{
		Public:      public,
		View:        view,
		Version:     version,
		Brand:       brand,
		Environment: cc,
		RecordCount: 0,
		TidbitIndex: fulltext.Tidbits{
			TotalDocs:  0,
			TotalTerms: 0,
		},
	}
	c.Version = flags.VersionCommit(version)
	if ctx == nil || db == nil {
		return &c
	}

	var stats model.Artifacts
	if err := stats.Public(ctx, db); err == nil {
		c.RecordCount = int64(stats.Count)
		c.TotalBytes = int64(stats.Bytes)
		c.MinYear = stats.MinYear
		c.MaxYear = stats.MaxYear
	}

	return &c
}

// flagParser is used to parse the command line arguments.
// If an error is returned, the application will exit with the error code.
// Otherwise, a negative value is returned to indicate the application should continue.
func flagParser(sl *slog.Logger, w io.Writer, cc *config.Config) flags.ExitCode {
	const msg = "command failed"
	if sl == nil || cc == nil {
		return flags.GenericErr
	}

	routesFn := func(out io.Writer, method string) error {
		serv := initialisation(context.Background(), nil, *cc)
		return serv.PrintRoutes(out, method)
	}
	exitCode, err := flags.Run(w, version, cc, routesFn)
	if err != nil {
		sl.Error(msg, slog.Int("exit_code", int(exitCode)), slog.Any("error", err))
		return exitCode
	}
	if use := exitCode >= flags.ExitOK; use {
		return exitCode
	}

	return flags.Continue
}

// opening prints the welcome to message and returns the number
// of artifacts kept in the database. It customizes the log level based
// on the number of records vs the expected number.
func opening(sl *slog.Logger, count int64) {
	if sl == nil {
		sl = slog.Default()
	}
	const msg = "Welcome to the Defacto2 web application"

	switch {
	case count == 0:
		s := ", but with no access to the database records"
		sl.Error(msg + s)
	case config.MinimumFiles > count:
		s := " with too few records"
		sl.Warn(msg+s,
			slog.Int64("record_count", count),
			slog.Int("minimum_requirement", config.MinimumFiles))
	default:
		sl.Info(msg, slog.Int64("Artifacts", count))
	}
}
